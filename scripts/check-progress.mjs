// Run after npm run build. Uses synthetic data only and serves on a temporary local port.
import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { readFile, access } from 'node:fs/promises';
import { createServer } from 'node:http';
import { once } from 'node:events';
import { resolve, relative, extname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const server = createServer(async (request, response) => {
  try {
    const path = decodeURIComponent(new URL(request.url, 'http://localhost').pathname);
    const file = resolve(root, '.' + (path === '/' ? '/index.html' : path));
    if (relative(root, file).startsWith('..')) throw new Error('Outside test root');
    const types = { '.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css' };
    response.setHeader('Content-Type', types[extname(file)] || 'application/octet-stream');
    response.end(await readFile(file));
  } catch { response.writeHead(404); response.end(); }
});
server.listen(0, '127.0.0.1');
await once(server, 'listening');
const origin = `http://127.0.0.1:${server.address().port}/`;
let browser;
try {
  let executablePath = process.env.CHROMIUM_PATH;
  if (!executablePath) { try { await access('/usr/bin/chromium'); executablePath = '/usr/bin/chromium'; } catch {} }
  browser = await chromium.launch({ executablePath, headless: true, args: ['--no-sandbox'] });
  const context = await browser.newContext({ viewport: { width: 1280, height: 900 } });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(origin);
  const key = 'helio-home:progress:v1';
  const stored = () => page.evaluate(key => localStorage.getItem(key), key);
  assert.equal(await stored(), null);
  assert.equal(await page.locator('#delete-progress').isDisabled(), true);
  await page.locator('#bill-kwh-0').fill('0');
  await page.locator('#bill-cost-0').fill('15.47');
  await page.locator('#bill-kwh-1').fill('800');
  await page.locator('#solarKw').fill('4.5');
  await page.locator('#customer').fill('PRIVATE CUSTOMER');
  assert.equal(await stored(), null);
  await page.locator('#save-progress').click();
  const partial = await stored();
  assert.equal(JSON.parse(partial).bills[0].kwh, 0);
  assert.equal(JSON.parse(partial).bills[1].cost, null);
  assert.doesNotMatch(partial, /PRIVATE CUSTOMER|customer|name|email|notes|ocr/i);
  await page.locator('#bill-kwh-1').fill('900');
  assert.match(await page.locator('#save-progress-status').textContent(), /Unsaved changes/);
  assert.equal(await stored(), partial);
  await page.reload();
  assert.equal(await page.locator('#bill-kwh-0').inputValue(), '0');
  assert.equal(await page.locator('#bill-cost-0').inputValue(), '15.47');
  assert.equal(await page.locator('#bill-kwh-1').inputValue(), '800');
  assert.equal(await page.locator('#bill-cost-1').inputValue(), '');
  assert.equal(await page.locator('#solarKw').inputValue(), '4.5');
  assert.equal(await page.locator('#customer').inputValue(), '');
  assert.match(await page.locator('#save-progress-status').textContent(), /restored/);
  await page.locator('#bill-cost-1').fill('-1');
  assert.equal(await page.locator('#save-progress').isDisabled(), true);
  assert.equal(await stored(), partial);
  await page.locator('#bill-cost-1').fill('');
  assert.equal(await page.locator('#save-progress').isEnabled(), true);
  await page.locator('#rate').fill('');
  await page.locator('#save-progress').click();
  await page.reload();
  assert.equal(await page.locator('#rate').inputValue(), '');
  assert.equal(await page.locator('#estimate-results').isVisible(), false);
  await page.locator('#reset').click();
  await page.locator('#review-example').click();
  await page.locator('#save-progress').click();
  await page.reload();
  assert.match(await page.locator('#review-progress').textContent(), /Includes example data/);
  assert.equal(await page.locator('#review-kwh').textContent(), '12,450 kWh');
  assert.equal(await page.locator('#recommendation-results').isVisible(), true);
  assert.equal(await page.locator('#comparison-results').isVisible(), true);
  await page.locator('#request-assessment').click();
  await page.locator('#assessment-form [name=name]').fill('PRIVATE NAME');
  await page.locator('#assessment-form [name=email]').fill('private@example.com');
  await page.locator('#assessment-form [name=notes]').fill('PRIVATE NOTES');
  // Trigger explicitly while the contact dialog is open to verify the serialization boundary.
  await page.locator('#save-progress').evaluate(button => button.click());
  const full = await stored();
  assert.doesNotMatch(full, /PRIVATE|private@|customer|email|notes|postal|image|filename|ocr/);
  await page.locator('#assessment-close').click();
  await page.locator('#bill-kwh-0').fill('1200');
  await page.locator('#save-progress').click();
  assert.equal(JSON.parse(await stored()).exampleFields.includes('bill-kwh-0'), false);
  await page.reload();
  assert.equal(JSON.parse(await stored()).exampleFields.includes('bill-kwh-0'), false);
  await page.evaluate(() => localStorage.setItem('unrelated-site-setting', 'keep'));
  await page.locator('#delete-progress').click();
  assert.equal(await stored(), null);
  assert.equal(await page.locator('#bill-kwh-0').inputValue(), '1200');
  await page.locator('#bill-kwh-0').fill('1300');
  assert.equal(await stored(), null);
  assert.equal(await page.evaluate(() => localStorage.getItem('unrelated-site-setting')), 'keep');
  await page.reload();
  assert.equal(await page.locator('#bill-kwh-0').inputValue(), '');
  await page.evaluate(key => localStorage.setItem(key, '{corrupt'), key);
  await page.reload();
  assert.match(await page.locator('#save-progress-status').textContent(), /could not be loaded/);
  assert.equal(await page.locator('#bill-kwh-0').inputValue(), '');
  assert.equal(await stored(), '{corrupt');
  await page.locator('#delete-progress').click();
  assert.equal(await stored(), null);
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.locator('.save-progress-panel').screenshot({ path: '/tmp/helio-save-progress-mobile.png' });
  await page.emulateMedia({ media: 'print' });
  assert.equal(await page.locator('.save-progress-panel').isVisible(), false);
  await page.emulateMedia({ media: 'screen' });

  const blocked = await context.newPage();
  blocked.on('pageerror', error => errors.push(error.message));
  await blocked.addInitScript(() => {
    for (const method of ['getItem', 'setItem', 'removeItem']) Storage.prototype[method] = () => { throw new DOMException('Blocked', 'SecurityError'); };
  });
  await blocked.goto(origin);
  assert.match(await blocked.locator('#save-progress-status').textContent(), /storage is unavailable/);
  await blocked.locator('#bill-kwh-0').fill('100');
  await blocked.locator('#save-progress').click();
  assert.match(await blocked.locator('#save-progress-status').textContent(), /could not be saved/);
  assert.equal(await blocked.locator('#bill-kwh-0').inputValue(), '100');
  assert.equal(await blocked.locator('#annual-savings').textContent(), '$1,256');
  await blocked.close();

  await page.evaluate(({ key, full }) => localStorage.setItem(key, full), { key, full });
  const quota = await context.newPage();
  quota.on('pageerror', error => errors.push(error.message));
  await quota.addInitScript(() => { Storage.prototype.setItem = () => { throw new DOMException('Full', 'QuotaExceededError'); }; });
  await quota.goto(origin);
  await quota.locator('#bill-kwh-0').fill('2000');
  await quota.locator('#save-progress').click();
  assert.match(await quota.locator('#save-progress-status').textContent(), /could not be saved/);
  assert.equal(await quota.evaluate(key => localStorage.getItem(key), key), full);
  await quota.close();
  const cannotDelete = await context.newPage();
  cannotDelete.on('pageerror', error => errors.push(error.message));
  await cannotDelete.addInitScript(() => { Storage.prototype.removeItem = () => { throw new DOMException('Blocked', 'SecurityError'); }; });
  await cannotDelete.goto(origin);
  await cannotDelete.locator('#delete-progress').click();
  assert.match(await cannotDelete.locator('#save-progress-status').textContent(), /could not be deleted/);
  assert.equal(await cannotDelete.evaluate(key => localStorage.getItem(key), key), full);
  await cannotDelete.close();
  assert.deepEqual(errors, []);
  console.log('PASS: opt-in save; partial numbers and zeros; reload restoration and recalculation; unsaved edits; sample provenance; contact exclusion; delete without auto-resave; unrelated storage retained; corrupt data; blocked/quota/deletion failures; mobile and print.');
} finally {
  await browser?.close();
  server.closeAllConnections();
  await new Promise(resolve => server.close(resolve));
}
